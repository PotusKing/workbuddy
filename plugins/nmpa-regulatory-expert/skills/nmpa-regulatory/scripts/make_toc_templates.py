"""
生成 NMPA 注册申报资料 ToC 模板（.docx）

依据：
  器械 — 2021 年第 121 号公告（附件 5 申报资料要求及说明、附件 4 格式要求）
  IVD  — 2021 年第 122 号公告（附件 4 申报资料要求及说明、附件 3 格式要求）

设计纪律：
  · 「原文要求」框内的文字逐字摘自 121/122 号公告，不改写、不增删
  · 「提示」标注来源条文，只放能从原文推出的程序性事实
  · 涉及审评尺度/实操惯例的，加【专家口径】或【草稿】前缀，与原文严格区分

用法：
  python make_toc_templates.py            # 生成全部
  python make_toc_templates.py --only device
"""
import os
import argparse
from docx import Document
from docx.shared import Pt, Cm, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH, WD_TAB_ALIGNMENT
from docx.enum.table import WD_TABLE_ALIGNMENT
from docx.oxml.ns import qn
from docx.oxml import OxmlElement

OUT_DIR = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                       "assets", "templates")

# ── 配色（灰度印刷友好）─────────────────────────────────────────────
C_TEXT = RGBColor(0x1A, 0x1A, 0x1A)
C_GRAY = RGBColor(0x59, 0x59, 0x59)
C_FAINT = RGBColor(0x8C, 0x8C, 0x8C)
C_ACCENT = RGBColor(0x8C, 0x2F, 0x1E)      # 提示 / 口径标记
SH_REQ = "F2F2F2"                          # 原文框底色
SH_HEAD = "D9D9D9"                         # 表头底色
SH_TIP = "FBF3E6"                          # 提示框底色


# ══════════════════════════════════════════════════════════════════
# 基础排版
# ══════════════════════════════════════════════════════════════════
def font(run, cn="宋体", size=10.5, bold=False, color=None, italic=False):
    run.font.name = "Times New Roman"
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.italic = italic
    if color is not None:
        run.font.color.rgb = color
    rpr = run._element.get_or_add_rPr()
    rf = rpr.find(qn("w:rFonts"))
    if rf is None:
        rf = OxmlElement("w:rFonts")
        rpr.append(rf)
    rf.set(qn("w:eastAsia"), cn)
    rf.set(qn("w:ascii"), "Times New Roman")
    rf.set(qn("w:hAnsi"), "Times New Roman")
    return run


def para(doc, text="", cn="宋体", size=10.5, bold=False, color=None, italic=False,
         align=None, before=0, after=4, line=1.45, indent=None, first_line=None):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.space_before = Pt(before)
    pf.space_after = Pt(after)
    pf.line_spacing = line
    if align is not None:
        p.alignment = align
    if indent is not None:
        pf.left_indent = Cm(indent)
    if first_line is not None:
        pf.first_line_indent = Cm(first_line)
    if text:
        font(p.add_run(text), cn=cn, size=size, bold=bold, color=color, italic=italic)
    return p


def heading(doc, text, level=1):
    """用内置 Heading 样式保住大纲导航，再覆盖字体"""
    p = doc.add_paragraph(style="Heading %d" % level)
    pf = p.paragraph_format
    if level == 1:
        pf.space_before = Pt(18)
        pf.space_after = Pt(8)
        font(p.add_run(text), cn="黑体", size=15, bold=True, color=C_TEXT)
    elif level == 2:
        pf.space_before = Pt(12)
        pf.space_after = Pt(5)
        font(p.add_run(text), cn="黑体", size=12, bold=True, color=C_TEXT)
    else:
        pf.space_before = Pt(8)
        pf.space_after = Pt(3)
        font(p.add_run(text), cn="黑体", size=10.5, bold=True, color=C_TEXT)
    return p


def shade(cell, hex_color):
    tcpr = cell._tc.get_or_add_tcPr()
    el = OxmlElement("w:shd")
    el.set(qn("w:val"), "clear")
    el.set(qn("w:color"), "auto")
    el.set(qn("w:fill"), hex_color)
    tcpr.append(el)


def cell_text(cell, text, cn="宋体", size=9, bold=False, color=None, align=None):
    cell.text = ""
    p = cell.paragraphs[0]
    p.paragraph_format.space_before = Pt(2)
    p.paragraph_format.space_after = Pt(2)
    p.paragraph_format.line_spacing = 1.2
    if align is not None:
        p.alignment = align
    font(p.add_run(text), cn=cn, size=size, bold=bold, color=color)
    return cell


def grid(doc, header, rows, widths, size=9, header_size=9):
    """带表头的表格；widths 单位 cm，超出版心时按比例压缩"""
    total = sum(widths)
    text_w = 21.0 - 2.3 - 2.3
    if total > text_w:
        widths = [w * text_w / total for w in widths]
    t = doc.add_table(rows=1, cols=len(header))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    # 固定列宽布局，避免 Word 自动拉伸
    tblpr = t._tbl.tblPr
    layout = OxmlElement("w:tblLayout")
    layout.set(qn("w:type"), "fixed")
    tblpr.append(layout)
    for i, h in enumerate(header):
        c = t.rows[0].cells[i]
        cell_text(c, h, cn="黑体", size=header_size, bold=True,
                  align=WD_ALIGN_PARAGRAPH.CENTER)
        shade(c, SH_HEAD)
    for r in rows:
        cells = t.add_row().cells
        for i, v in enumerate(r):
            cell_text(cells[i], v, size=size)
    for row in t.rows:
        for i, w in enumerate(widths):
            row.cells[i].width = Cm(w)
    # 表头跨页重复
    trpr = t.rows[0]._tr.get_or_add_trPr()
    el = OxmlElement("w:tblHeader")
    el.set(qn("w:val"), "true")
    trpr.append(el)
    return t


def box(doc, lines, fill=SH_REQ, label=None, label_color=C_GRAY, size=9.5):
    """单格底纹框：原文要求 / 提示"""
    t = doc.add_table(rows=1, cols=1)
    t.style = "Table Grid"
    t.autofit = False
    c = t.rows[0].cells[0]
    c.width = Cm(16.4)
    shade(c, fill)
    c.text = ""
    first = True
    if label:
        p0 = c.paragraphs[0]
        p0.paragraph_format.space_before = Pt(3)
        p0.paragraph_format.space_after = Pt(2)
        p0.paragraph_format.line_spacing = 1.25
        font(p0.add_run(label), cn="黑体", size=size - 0.5, bold=True, color=label_color)
        first = False
    for ln in lines:
        p = c.paragraphs[0] if first else c.add_paragraph()
        first = False
        p.paragraph_format.space_before = Pt(1)
        p.paragraph_format.space_after = Pt(3)
        p.paragraph_format.line_spacing = 1.3
        font(p.add_run(ln), cn="宋体", size=size, color=C_GRAY)
    para(doc, "", size=4, after=0)
    return t


def req_box(doc, text):
    box(doc, [text], fill=SH_REQ, label="原文要求", label_color=C_GRAY)


def tip_box(doc, text, tag="提示"):
    box(doc, [text], fill=SH_TIP, label="【%s】" % tag, label_color=C_ACCENT, size=9)


def checks(doc, items, indent=0.4):
    for it in items:
        p = doc.add_paragraph()
        pf = p.paragraph_format
        pf.left_indent = Cm(indent)
        pf.space_before = Pt(0)
        pf.space_after = Pt(2)
        pf.line_spacing = 1.4
        font(p.add_run("□  "), size=10.5, color=C_GRAY)
        font(p.add_run(it), size=10)


def fill(doc, hint="（在此填写）"):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.left_indent = Cm(0.4)
    pf.space_before = Pt(2)
    pf.space_after = Pt(8)
    pf.line_spacing = 1.4
    font(p.add_run(hint), size=9.5, color=C_FAINT, italic=True)
    # 下边框当书写线
    ppr = p._p.get_or_add_pPr()
    pbdr = OxmlElement("w:pBdr")
    bottom = OxmlElement("w:bottom")
    bottom.set(qn("w:val"), "dotted")
    bottom.set(qn("w:sz"), "6")
    bottom.set(qn("w:space"), "1")
    bottom.set(qn("w:color"), "BFBFBF")
    pbdr.append(bottom)
    ppr.append(pbdr)


def page_break(doc):
    doc.add_page_break()


def add_page_footer(section, note):
    footer = section.footer
    p = footer.paragraphs[0]
    p.paragraph_format.space_before = Pt(0)
    p.paragraph_format.space_after = Pt(0)
    # 右侧制表位：页码右对齐到版心右边界
    tabs = p.paragraph_format.tab_stops
    tabs.add_tab_stop(Cm(16.4), WD_TAB_ALIGNMENT.RIGHT)
    font(p.add_run(note), size=8, color=C_FAINT)
    p.add_run("\t")
    font(p.add_run("第 "), size=8, color=C_FAINT)
    r = p.add_run()
    font(r, size=8, color=C_FAINT)
    f1 = OxmlElement("w:fldChar"); f1.set(qn("w:fldCharType"), "begin")
    it = OxmlElement("w:instrText"); it.set(qn("xml:space"), "preserve"); it.text = "PAGE"
    f2 = OxmlElement("w:fldChar"); f2.set(qn("w:fldCharType"), "end")
    r._r.append(f1); r._r.append(it); r._r.append(f2)
    font(p.add_run(" 页"), size=8, color=C_FAINT)
    # 底部细线
    ppr = p._p.get_or_add_pPr()
    pbdr = OxmlElement("w:pBdr")
    top = OxmlElement("w:top")
    top.set(qn("w:val"), "single"); top.set(qn("w:sz"), "4")
    top.set(qn("w:space"), "4"); top.set(qn("w:color"), "BFBFBF")
    pbdr.append(top)
    ppr.append(pbdr)


