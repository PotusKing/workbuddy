def new_doc(title_note):
    doc = Document()
    # 正文默认样式
    st = doc.styles["Normal"]
    st.font.name = "Times New Roman"
    st.font.size = Pt(10.5)
    st.element.rPr.rFonts.set(qn("w:eastAsia"), "宋体")
    sec = doc.sections[0]
    sec.page_width = Cm(21.0)
    sec.page_height = Cm(29.7)
    sec.left_margin = Cm(2.3)
    sec.right_margin = Cm(2.3)
    sec.top_margin = Cm(2.3)
    sec.bottom_margin = Cm(2.0)
    add_page_footer(sec, title_note)
    return doc


def cover(doc, kind, scope, basis, authority):
    para(doc, "", after=60)
    para(doc, "医疗器械注册申报资料", cn="黑体", size=26, bold=True,
         align=WD_ALIGN_PARAGRAPH.CENTER, after=6)
    para(doc, kind, cn="黑体", size=18, bold=False,
         align=WD_ALIGN_PARAGRAPH.CENTER, color=C_GRAY, after=4)
    para(doc, "编 制 模 板", cn="黑体", size=13, color=C_FAINT,
         align=WD_ALIGN_PARAGRAPH.CENTER, after=40)

    t = doc.add_table(rows=0, cols=2)
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    rows = [
        ("产品名称", ""),
        ("型号、规格", ""),
        ("注册申请人", ""),
        ("申报类型", scope),
        ("注册分类", "□ 第二类    □ 第三类"),
        ("编制日期", ""),
        ("版　　本", "V1.0"),
    ]
    for k, v in rows:
        cells = t.add_row().cells
        cell_text(cells[0], k, cn="黑体", size=10, bold=True,
                  align=WD_ALIGN_PARAGRAPH.CENTER)
        shade(cells[0], SH_REQ)
        cell_text(cells[1], v, size=10)
        cells[0].width = Cm(4.2)
        cells[1].width = Cm(8.8)

    para(doc, "", after=50)
    para(doc, "编制依据", cn="黑体", size=9.5, bold=True,
         align=WD_ALIGN_PARAGRAPH.CENTER, color=C_GRAY, after=2)
    for line in basis:
        para(doc, line, size=9, color=C_GRAY, align=WD_ALIGN_PARAGRAPH.CENTER, after=2)
    para(doc, "", after=14)
    para(doc, authority, size=9, color=C_FAINT, align=WD_ALIGN_PARAGRAPH.CENTER)
    page_break(doc)


def usage_page(doc, form_rules, sign_rules, e_rules, extra=None):
    heading(doc, "使用说明", 1)
    para(doc, "本模板是申报资料的结构与写作载体，不是审评口径。填写内容必须由申请人依据产品实际"
              "自行完成；模板中的灰色「原文要求」框逐字摘自公告原文，是形式审查与发补的直接依据，"
              "不得删改。", size=10)
    para(doc, "", after=2)

    heading(doc, "一、三条形式审查硬线（最高频退回点）", 2)
    para(doc, "下列三条并非经验之谈，均为公告附件「格式要求」明文规定，形式审查必查。编制完成、送审前逐条打勾确认：", size=10)
    checks(doc, [
        "每章必须有 X.1 章节目录，含本章全部一级、二级标题，并注明各项页码（模板每章首页已备目录表）；",
        "每项二级标题对应的资料单独编制页码——不是整本连续页码，这一条踩得最多；",
        "除关联文件外全部中文；外文证明性文件须附中文译本并由代理人签章，据外文翻译的资料须同时提供原文。",
    ])

    heading(doc, "二、形式要求（原文）", 2)
    for i, r in enumerate(form_rules, 1):
        p = doc.add_paragraph()
        p.paragraph_format.left_indent = Cm(0.4)
        p.paragraph_format.space_after = Pt(2)
        p.paragraph_format.line_spacing = 1.4
        font(p.add_run("%d. " % i), size=9.5, bold=True, color=C_GRAY)
        font(p.add_run(r), size=9.5, color=C_GRAY)

    heading(doc, "三、签章与公证要求（原文）", 2)
    for i, r in enumerate(sign_rules, 1):
        p = doc.add_paragraph()
        p.paragraph_format.left_indent = Cm(0.4)
        p.paragraph_format.space_after = Pt(2)
        p.paragraph_format.line_spacing = 1.4
        font(p.add_run("%d. " % i), size=9.5, bold=True, color=C_GRAY)
        font(p.add_run(r), size=9.5, color=C_GRAY)

    heading(doc, "四、电子文档要求（原文）", 2)
    checks(doc, e_rules)

    if extra:
        heading(doc, "五、本模板的使用边界", 2)
        for e in extra:
            p = doc.add_paragraph()
            p.paragraph_format.left_indent = Cm(0.4)
            p.paragraph_format.space_after = Pt(3)
            p.paragraph_format.line_spacing = 1.4
            font(p.add_run("· "), size=9.5, color=C_ACCENT)
            font(p.add_run(e), size=9.5, color=C_GRAY)
    page_break(doc)


def chapter_head(doc, no, title, intro, toc_rows):
    heading(doc, "%s  %s" % (no, title), 1)
    if intro:
        para(doc, intro, size=9.5, color=C_GRAY, after=6)
    # 本章目录（即 X.1 章节目录的现成骨架）
    para(doc, "本章目录（对应 %s.1 章节目录）" % no, cn="黑体", size=9.5, bold=True,
         color=C_GRAY, after=3)
    grid(doc, ["编号", "二级标题", "页数", "页码"],
         [[c, t, "", ""] for c, t in toc_rows],
         widths=[1.8, 10.2, 2.0, 2.4])
    para(doc, "", after=4)


def item(doc, code, title, req=None, subs=None, table=None, tip=None, fillhint=None):
    heading(doc, "%s  %s" % (code, title), 2)
    if req:
        req_box(doc, req)
    if subs:
        checks(doc, subs)
    if table:
        header, rows, widths = table
        grid(doc, header, rows, widths)
        para(doc, "", size=4, after=2)
    if tip:
        tip_box(doc, tip)
    fill(doc, fillhint or "（在此填写）")


